"""Правило: карточка учит отдельное слово или целую фразу."""

import re

# Пометка в скобках — комментарий к форме («три (муж. род)»), а не содержание
# карточки, поэтому в счёт слов она не идёт. `classification` чистит перевод так же,
# но своей копией: там правило разбирает смысл перевода, а здесь считает слова.
_NOTE = re.compile(r"\([^)]*\)")


def is_word(arabic: str, translation_ru: str) -> bool:
    """Отдельное слово — карточка, где одно слово хотя бы с одной стороны."""
    return len(arabic.split()) == 1 or len(_NOTE.sub(" ", translation_ru).split()) == 1
