_WORD = re.compile(r"[а-яёa-z]+", re.IGNORECASE)


def _clean(translation: str) -> str:
    """Перевод без грамматической пометки, в нижнем регистре и с одиночными пробелами.

    Пробелы схлопываются потому, что вырезанная пометка оставляет после себя дыру:
    без этого «пальто (мн. ч.)» не совпало бы со списком целиком.
    """
    return " ".join(_NOTE.sub(" ", translation).lower().split())


def _has_stem(text: str, stems: tuple[str, ...]) -> bool:
    return any(re.search(rf"\b{stem}", text) for stem in stems)


def themes_for(translation_ru: str) -> list[str]:
    """Темы карточки по её переводу, в порядке объявления `Theme`.

    Тема ставится по тому, что карточка отрабатывает, а не по всем словам в ней:
    иначе «Существительные» собрали бы почти всю базу — существительное есть
    в любом предложении. Поэтому существительные — остаток: их получает карточка,
    которую не забрала ни одна другая тема.
    """
    text = _clean(translation_ru)
    words = set(_WORD.findall(text))
    found: set[str] = set()

    for theme, stems in _STEMS.items():
        if _has_stem(text, stems):
            found.add(theme)

    if words & _NUMERALS:
        found.add(Theme.NUMBERS)

    if words & _UNCHANGING_SIGNS:
        found.add(Theme.ANTONYMS)

    # Карточка самого служебного слова: «из», «я», «справа от».
    if text in _FUNCTION_CARDS:
        found.add(Theme.QUESTIONS)

    # Вопрос — всегда отработка вопроса, даже если внутри есть глагол.
    if "?" in translation_ru or words & _INTERROGATIVES or "частица вопроса" in text:
        found.add(Theme.QUESTIONS)

    # Предлог тянет карточку в служебную тему только когда глагола нет: в «мужчина
    # идёт в мечеть» отрабатывается глагол, а «книга на столе» — как раз предлог.
    if Theme.VERBS not in found and words & _PREPOSITIONS:
        found.add(Theme.QUESTIONS)

    if not found:
        found.add(Theme.NOUNS)

    if text in _DIALOG_3:
        found.add(Theme.DIALOG_3)

    return [theme for theme in Theme.values if theme in found]
